"""QuantCheck: deterministic point-in-time financial data reliability auditing.

The canonical contract layer — strict JSON value types, immutable domain
schemas, one canonical serialization path, SHA-256 hashing, and deterministic
stable identifiers — is implemented. The deterministic reviewed fixture,
point-in-time snapshot construction with explicit revision ordering, and the
``sanitize_for_audit`` trust boundary are implemented. Recovery Phase 3 adds
the narrow Look-Ahead injection, manifest-blind detection, exact scoring,
manifest-assisted replay, and controlled availability-count comparison. The
narrow one-CIK SEC Company Facts adapter adds cache-first retrieval, offline
replay, and explicit allowlist normalization. Recovery Phase 5 adds the
narrow Unit Drift scale-corruption, local detection, exact scoring,
manifest-assisted replay, and aggregate-value comparison. Recovery Phase 7
adds explicit-history Revision Overwrite injection, temporal detection, exact
scoring/replay, and controlled growth-ranking sensitivity. Recovery Phase 8
adds the benchmark layer: strict configuration/expansion, an
all-four-detector dispatcher, public/private atomic artifact persistence,
structured failures, safe resume, and public-only aggregation. Recovery
Phase 9 adds the contracted Typer CLI and a saved-stage
``inject``/``audit``/``evaluate`` workflow (``quantcheck.saved_case_workflow``)
over the same benchmark case type and dispatch functions, reachable only
through ``quantcheck.cli`` so that a bare ``import quantcheck`` never pulls in
Typer. Presentation and release evidence are not implemented.
"""

